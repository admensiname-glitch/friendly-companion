FROM seed s
JOIN public.disciplines d
  ON d.course_id=(SELECT id FROM public.courses WHERE slug='pedagogia' LIMIT 1)
 AND lower(d.name)=lower(s.discipline_name)
WHERE NOT EXISTS (
  SELECT 1 FROM public.topics t
  WHERE t.discipline_id=d.id
    AND lower(t.name)=lower(s.topic_name)
